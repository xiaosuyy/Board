#!/usr/bin/env python3
"""Generate the pinyin search index for the emoji panel.

Reads assets/emoji/cldr.tsv and zh-extra.tsv, converts every Chinese keyword
(full pinyin + initials) to a token, and writes assets/emoji/search.tsv:

    <token>\t<emoji> <emoji> ...

Chat-common words from zh-extra.tsv are written before CLDR keywords, so the
panel ranks them first. Requires pypinyin (build-time only; not shipped).
"""

from __future__ import annotations

import pathlib

from pypinyin import lazy_pinyin

ROOT = pathlib.Path(__file__).resolve().parents[1]
EMOJI_DIR = ROOT / "android" / "app" / "src" / "main" / "assets" / "emoji"


def is_cjk(char: str) -> bool:
    return "\u4e00" <= char <= "\u9fff"


def tokens_for(word: str) -> list[str]:
    word = word.strip()
    if not word or not any(is_cjk(char) for char in word):
        return []
    parts = [part.lower() for part in lazy_pinyin(word) if part]
    full = "".join(parts)
    initials = "".join(part[0] for part in parts)
    return [token for token in (full, initials) if token]


def add(index: dict[str, list[str]], word: str, emoji: str) -> None:
    for token in tokens_for(word):
        bucket = index.setdefault(token, [])
        if emoji not in bucket:
            bucket.append(emoji)


def read_rows(path: pathlib.Path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        yield line.split("\t")


def main() -> None:
    index: dict[str, list[str]] = {}

    # Chat-common words first: they should outrank generic CLDR keywords.
    for row in read_rows(EMOJI_DIR / "zh-extra.tsv"):
        if len(row) < 2:
            continue
        word, emojis = row[0], row[1].split()
        for emoji in emojis:
            add(index, word, emoji)

    for row in read_rows(EMOJI_DIR / "cldr.tsv"):
        if len(row) < 2:
            continue
        emoji, keywords = row[0], row[1].split("|")
        for word in keywords:
            add(index, word, emoji)

    lines = [
        "# Generated by tools/gen_emoji_search.py — do not edit.",
        "# Pinyin/initial search tokens for emoji keywords.",
        "# Sources: Unicode CLDR (Unicode License v3), zh-extra.tsv.",
    ]
    for token in sorted(index):
        lines.append(f"{token}\t{' '.join(index[token])}")

    target = EMOJI_DIR / "search.tsv"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target} ({len(index)} tokens)")


if __name__ == "__main__":
    main()
